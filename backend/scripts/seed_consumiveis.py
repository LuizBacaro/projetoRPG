def seed_consumiveis(db) -> None:
    from app.games.dnd35.models.consumivel import Consumivel
    from app.games.dnd35.models.consumivel import ConsumivelJogador
    from app.shared.core.config import settings

    nomes_legacy_remover = {
        "Permite que uma magia de até 4º nível seja 77–81 invocar criaturas VII",
        "Supondo que nenhum componente material 71–76 alterar forma",
        "Supondo uma área equivalente a um cubo 32–37 portal",
        "XP. 67–70 sombras",
        "invocar criaturas VII",
        "alterar forma",
        "portal",
    }

    # Oculta entradas legadas do catálogo sem apagar histórico em fichas.
    # Mantemos deleted_at nulo para não quebrar consumíveis já vinculados ao jogador.
    (
        db.query(Consumivel)
        .filter(Consumivel.nome.in_(nomes_legacy_remover), Consumivel.deleted_at.is_(None))
        .update({"ativo": False}, synchronize_session=False)
    )

    dados_seed = [
        d for d in CONSUMIVEIS_DADOS
        if d.get("nome") not in nomes_legacy_remover
    ]
    if settings.ENVIRONMENT == "production" and not settings.CONSUMIVEIS_SEED_PERGAMINHOS:
        dados_seed = [
            d for d in dados_seed
            if (d.get("categoria") or "").strip().lower() != "pergaminho"
        ]

    nomes_seed = {d["nome"] for d in dados_seed}
    usados = {
        row[0]
        for row in db.query(ConsumivelJogador.consumivel_id).distinct().all()
        if row[0] is not None
    }
    legado = (
        db.query(Consumivel)
        .filter(Consumivel.deleted_at.is_(None))
        .all()
    )
    removidos = 0
    for item in legado:
        if item.nome not in nomes_seed and item.id not in usados:
            db.delete(item)
            removidos += 1
    if removidos:
        db.flush()

    inseridos = 0
    atualizados = 0
    for data in dados_seed:
        row = (
            db.query(Consumivel)
            .filter(Consumivel.nome == data["nome"], Consumivel.deleted_at.is_(None))
            .first()
        )
        campos = {
            "descricao": data.get("descricao"),
            "pagina_referencia": data.get("pagina_referencia"),
            "categoria": data.get("categoria"),
            "tipo": data.get("tipo"),
            "custo": data.get("custo"),
            "peso": data.get("peso"),
            "ativo": data.get("ativo", True),
        }
        if row:
            for k, v in campos.items():
                setattr(row, k, v)
            atualizados += 1
        else:
            db.add(
                Consumivel(
                    nome=data["nome"],
                    **campos,
                    criado_em=datetime.now(timezone.utc),
                )
            )
            inseridos += 1

    db.commit()
    print(
        f"✅ Catálogo de consumíveis sincronizado: +{inseridos} inseridos, "
        f"{atualizados} atualizados, {removidos} removidos (total: {len(dados_seed)})."
    )
